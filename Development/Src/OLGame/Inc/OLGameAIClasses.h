		out_PolyShape.AddItem(Location + FVector(CylinderComponent->CollisionRadius+BUFFER,CylinderComponent->CollisionRadius+BUFFER,0.f));
		out_PolyShape.AddItem(Location + FVector(-(CylinderComponent->CollisionRadius+BUFFER),CylinderComponent->CollisionRadius+BUFFER,0.f));
