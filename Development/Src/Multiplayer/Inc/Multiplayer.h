// ============================================================================
// FMpConnection — persistent UDP connection that survives map transitions.
// Inherits FUdpLink directly (owns the socket).
// Lives as a global singleton; never destroyed while the process runs.
// Ticked via FMpConnectionTicker which is registered after engine init.
// ============================================================================

class FMpConnection : public FUdpLink
{
public:
    // Session state
    UBOOL   bIsConnected;
    UBOOL   bIsHandshaked;
    UBOOL   bResolved;
    UBOOL   bCancelled;   // set by CancelConnect(); suppresses auto-reconnect in Tick
    INT     LocalPlayerID;
    INT     HelloAttempt;
    FLOAT   LastReceivedTime;
    FLOAT   HelloTimer;         // seconds until next HELLO retry
    FLOAT   HeartbeatTimer;     // seconds until next heartbeat check

    // Server address (filled on Resolve)
    FIpAddr ServerAddr;

    // Config (read from DefaultMultiplayer.ini on first connect)
    FString IP;
    FString UdpPort;
    FString Username;
    FString RoomCode;
    FString Password;
    UBOOL   SyncInteractable;
    UBOOL   SyncEnemies;
    UBOOL   SyncMatinees;
    UBOOL   SyncPickups;
    UBOOL   SpeedrunMode;

    // Initialized flag — set after first LoadConfig(); avoids re-reading ini.

    // Session token (32 bytes) — received in SRV_READY, echoed as hex64 in HELLO
    // for reliable NAT rebind slot identification.
    BYTE SessionToken[32];

    // Reliable transport session; conn_id comes from SRV_READY, keys from the handshake.
    OlConn Conn;
    OlHsClient Hs;

    // World session. WorldEpoch is 0 until the server has placed us in a world.
    WORD    WorldEpoch;
    INT     SimOwnerID;          // client running enemy AI; 0 until the server names one
    UBOOL   bInBaseline;         // between SESS_WORLD and SESS_BASELINE_END
    UBOOL   bTravelPending;      // SESS_TRAVEL received but no controller to apply it yet
    UBOOL   bSkipNextEnter;      // the checkpoint restart already reported the world
    FString TravelCheckpoint;    // restart at this checkpoint belongs to SESS_TRAVEL
    FString TravelPersist;
    FString LastReportedCheckpoint;
    UBOOL bHasSessionToken;

    // Persistent player registry — survives map transitions.
    // Keyed by PlayerID; populated on NICK, cleared on DISCONNECT.
    struct FRemoteNick { INT PlayerID; FString Username; };
    TArray<FRemoteNick> KnownPlayers;

    // Persistent server info — survives map transitions.
    FString ServerName;
    INT     OnlineCount;

    FLOAT   PingTimer;

    // P2P mode — connect to host via Steam P2P instead of direct UDP.
    // When bP2PMode is TRUE, FP2PBridge is used as a loopback tunnel.
    // HostSteamID is the 64-bit SteamID of the host.
    UBOOL   bP2PMode;
    QWORD   HostSteamID;

    // Set by LoadConfig() if -openol_host was on the command line (Steam cold-launch).
    UBOOL   bP2PColdLaunch;
    FString P2PColdLaunchHost;
    FString P2PColdLaunchRoom;

    // Set when the local player is hosting — Connect() skips LoadConfig() so
    // caller-supplied IP/Port/RoomCode are not overwritten by the ini.
    UBOOL   bHostMode;

    FMpConnection()
        : bIsConnected(FALSE), bIsHandshaked(FALSE), bResolved(FALSE), bCancelled(FALSE)
        , LocalPlayerID(0), HelloAttempt(0), LastReceivedTime(0.f)
        , HelloTimer(0.f), HeartbeatTimer(5.f)
        , SyncInteractable(TRUE), SyncEnemies(TRUE)
        , SyncMatinees(TRUE), SyncPickups(TRUE), SpeedrunMode(FALSE)
        , bHasSessionToken(FALSE)
        , WorldEpoch(0), SimOwnerID(0), bInBaseline(FALSE), bTravelPending(FALSE), bSkipNextEnter(FALSE)
        , OnlineCount(0), PingTimer(5.f)
        , bP2PMode(FALSE), HostSteamID(0)
        , bP2PColdLaunch(FALSE)
        , bHostMode(FALSE)
    {
        appMemzero(&ServerAddr, sizeof(ServerAddr));
        appMemzero(SessionToken, sizeof(SessionToken));
        appMemzero(&Conn, sizeof(Conn));
        appMemzero(&Hs, sizeof(Hs));
    }

    // Connect via Steam P2P to the given host SteamID.
    // Sets up FP2PBridge loopback and points ServerAddr to the virtual port.
    void ConnectP2P(QWORD InHostSteamID, WORD InRelayPort, const FString& InRoomCode, const FString& InPassword);

    // Load settings from DefaultMultiplayer.ini ([Multiplayer.MultiplayerLink]).
    void LoadConfig();

    // Kick off DNS resolve + bind. Safe to call multiple times (no-op if already resolved).
    void Connect();

    // Send raw bytes prepending [type(1)][player_id LE4]. Safe to call any time.
    void SendBinary(BYTE* Data, INT Count);

    // Send a text line to the server (legacy path).
    void SendText(const FString& Line);

    // FUdpLink override — receives all incoming UDP datagrams.
    virtual void OnReceivedData(FIpAddr SrcAddr, BYTE* Data, INT Count);

    // Handles one message: a raw SRV packet or a message from the transport.
    void HandleMessage(BYTE* Data, INT Count);
    static void TransportDeliver(void* User, int Lane, uint8_t* Msg, int Len);
    static void TransportSend(void* User, const uint8_t* Datagram, int Len);

    // Send DISCONNECT packet to server and reset connection state.
    void Disconnect();

    // Abort an in-progress connection attempt (Resolving or Connecting) without
    // sending DISCONNECT. Safe to call when already disconnected (no-op).
    void CancelConnect();

    // Called every frame by FMpConnectionTicker.
    void Tick(FLOAT DeltaTime);
};

